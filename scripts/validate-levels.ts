/**
 * Level validator: a bot plays every level with the real simulation (fixed timestep, deterministic) and must
 * finish it with all three golden acorns using the given seeds; at every decision point each seed card is planted
 * and must work (the answer) or fail (every other card). Writes docs/levels-report.md; exits 1 if any level fails.
 * usage: npm run validate:levels
 */
import { writeFileSync } from 'node:fs';
import { solve } from '../src/game/bot';
import { LEVELS } from '../src/game/levels';
import { newSim, step, choose } from '../src/game/sim';
import { Replay } from '../src/game/bot';

const rows: string[] = [];
const details: string[] = [];
let failed = 0;
for (const L of LEVELS) {
  const p = solve(L);
  const problems: string[] = [];
  if (!p.ok) problems.push(`not finished with 3 acorns (reached x ${p.final.x.toFixed(1)} of ${L.goalX.toFixed(1)}, ${p.final.acorns} acorns)`);
  if (p.dps.length !== L.dps.length) problems.push(`only ${p.dps.length} of ${L.dps.length} decision points reached`);
  for (const d of p.dps)
    for (const c of d.cards) {
      if (c.kind === d.answer && !c.ok) problems.push(`decision ${d.dp + 1}: the answer (${c.kind}) fails (${c.reason})`);
      if (c.kind !== d.answer && c.ok) problems.push(`decision ${d.dp + 1}: wrong card ${c.kind} works`);
    }
  if (p.final.seeds < 0) problems.push('ran out of seeds');
  // replaying the plan from scratch gives the same result (determinism)
  const s = newSim(L);
  const r = new Replay(p);
  for (let i = 0; i < 60 * 300 && s.mode !== 'won' && s.mode !== 'lost'; i++) {
    if (s.mode === 'decide') {
      const k = r.choice();
      if (!k || !choose(L, s, k)) break;
    }
    step(L, s, r.input(s));
  }
  if (p.ok && (s.mode !== 'won' || s.acorns !== 3)) problems.push('replay of the plan does not reproduce the win');
  if (p.seconds < 45 || p.seconds > 120) problems.push(`length ${p.seconds.toFixed(0)} s is outside 45-120 s`);
  if (problems.length) failed++;
  const gems = L.pickups.filter((q) => q.kind === 'gem').length;
  rows.push(`| ${L.id} | ${problems.length ? 'FAIL' : 'ok'} | ${p.seconds.toFixed(1)} s | ${p.final.acorns}/3 | ${p.final.gems}/${gems} | ${L.seeds - p.final.seeds}/${L.seeds} | ${L.dps.length} |`);
  details.push(`### ${L.id}\n`);
  if (!L.dps.length) details.push('No decision points.\n');
  for (const d of p.dps) {
    const dp = L.dps[d.dp];
    details.push(`- Decision ${d.dp + 1} (${dp.obstacle}${dp.width ? `, ${dp.width} wide` : ''}${dp.height && dp.obstacle === 'wall' ? `, ${dp.height} high` : ''}), answer **${d.answer}**: ` + d.cards.map((c) => `${c.kind} ${c.ok ? 'crosses' : `fails (${c.reason})`}`).join(', '));
  }
  for (const pr of problems) details.push(`- **Problem:** ${pr}`);
  details.push('');
}
const md = `# Level validator report

Generated by \`npm run validate:levels\` (scripts/validate-levels.ts). A beam-search bot plays each level with the
real simulation (src/game/sim.ts, fixed 60 Hz timestep, no randomness) using jump / hold / duck inputs in 50 ms
slices. A level passes when the bot finishes it with all 3 golden acorns using only the level's seeds, every
decision point's answer crosses and every other card fails, the recorded inputs replay to the same win, and the run
lasts 45-120 s.

| Level | Result | Bot time | Acorns | Gems | Seeds used | Decision points |
| --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}

## Decision points

${details.join('\n')}
`;
writeFileSync('docs/levels-report.md', md);
console.log(rows.join('\n'));
if (failed) {
  console.error(`${failed} level(s) failed`);
  process.exit(1);
}
